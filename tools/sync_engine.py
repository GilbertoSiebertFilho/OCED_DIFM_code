# -*- coding: utf-8 -*-
"""Copy the cleaning engine of OCED into this package (src/oced_clean/_engine) from a git checkout of OCED.

    python tools/sync_engine.py --oced <path to an OCED clone> [--ref <commit, tag or branch>] [--expect-subject TEXT]
    python tools/sync_engine.py --check          # the copied files still are what the manifest says (no hand edits)

The engine is not rewritten: every file is the committed file of OCED, byte for byte, except for the changes listed
in PATCHES below, each of which must match the source exactly the number of times it says (a change in OCED that
moves one of them stops the sync with a message instead of producing a silently different engine).

  1. package name   OCED imports its engine as the top-level package `engine`; here it lives inside this package, so
                    `from engine...` / `import engine...` become `from oced_clean._engine...` (and the one module name
                    built as a string for importlib).
  2. scikit-image   the cleaning module imports skimage at the top for the overlap raster of OCED's other cleaning
                    method, which this package never runs; the import is made lazy so scikit-image is not needed.
  3. no report      engine/report (the PDF report: reportlab, PyMuPDF, matplotlib) is not copied; a stub module with
                    a do-nothing make_report() takes its place. The figures are switched off at run time by
                    oced_clean._lean (nothing in the copied files changes for that).

Files are read from the commit itself (git show <ref>:<path>), never from the working tree, so local edits, line-ending
conversion and untracked files of the checkout cannot reach this package. The manifest
src/oced_clean/_engine/ENGINE_SOURCE.json records the commit, every file's hash before and after the patches, and the
patches applied; tests/test_engine_manifest.py checks the copied files against it.
"""
from __future__ import annotations

import argparse
import ast
import datetime as _dt
import hashlib
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PKG = "oced_clean._engine"
DEST = os.path.join(ROOT, "src", "oced_clean", "_engine")
TEST_DEST = os.path.join(ROOT, "tests", "oced_synthetic")
TEST_PKG = "tests.oced_synthetic"
MANIFEST = os.path.join(DEST, "ENGINE_SOURCE.json")
TEST_MANIFEST = os.path.join(TEST_DEST, "SOURCE.json")

# the engine modules of the route raw data -> import as SMS -> SMS 3-sigma cleaning -> clean shapefile. The decoders
# are listed here as they were when this was written; the sync adds every other decoder OCED's DECODERS list names
# (decoders_of below), so a format OCED gains comes in without an edit here.
ENGINE_FILES = [
    "engine/__init__.py",
    "engine/run.py",
    "engine/sms_import.py",
    "engine/difm.py",                    # the writer of the shapefile for DIFM (new in OCED 0.3.0)
    "engine/clean/__init__.py",
    "engine/clean/yield_clean.py",
    "engine/clean/sms3sigma.py",
    "engine/clean/sms_swath.py",
    "engine/clean/aoi.py",
    "engine/clean/sessions.py",
    "engine/clean/machines.py",
    "engine/clean/applied3s.py",
    "engine/formats/__init__.py",
    "engine/formats/common.py",
    "engine/formats/detect.py",
    "engine/formats/cnh_cn1.py",
    "engine/formats/jd_gs3_rcd.py",
    "engine/formats/jd_jdl.py",
    "engine/formats/ops_sections.py",
    "engine/formats/kml_points.py",
]
# OCED's own synthetic-data generators (made-up numbers only), for this package's tests. jd_jdl_write is the encoder
# the synthetic .jdl card is built with (test support only: the package itself never writes monitor formats). The
# GreenStar 3 card and the Operations Center exports are generated by helpers that live inside two of OCED's test
# modules: those are copied under names pytest does not collect, and only their helpers are called.
TEST_FILES = {
    "tests/synthetic.py": "synthetic.py",
    "tests/synthetic_cn1.py": "synthetic_cn1.py",
    "tests/synthetic_combines.py": "synthetic_combines.py",
    "tests/synthetic_jdl.py": "synthetic_jdl.py",
    "tests/test_jd_gs3_rcd.py": "gs3_card.py",
    "tests/test_inputs.py": "ops_exports.py",
    "engine/formats/jd_jdl_write.py": "jd_jdl_write.py",
}

IMPORT_RE = re.compile(r"^([ \t]*(?:from|import)[ \t]+)engine(?=[. \t])", re.M)
TESTS_IMPORT_RE = re.compile(r"^([ \t]*(?:from|import)[ \t]+)tests\.(synthetic\w*)", re.M)
REL_IMPORT_RE = re.compile(r"^([ \t]*from[ \t]+)\.([ \t]+import[ \t]+)", re.M)

# (file, description, old text, new text, exact number of matches)
PATCHES = [
    ("engine/formats/detect.py",
     "module name built as a string for importlib: the engine's package name inside this package",
     'importlib.import_module(f"engine.formats.{format_id}")',
     'importlib.import_module(f"' + PKG + '.formats.{format_id}")', 1),
    ("engine/clean/yield_clean.py",
     "scikit-image imported only when the overlap raster of OCED's other cleaning method runs (never here)",
     "from skimage.draw import polygon as sk_polygon\n",
     "def sk_polygon(*args, **kwargs):          # oced_clean: lazy import (scikit-image is not needed by the SMS route)\n"
     "    from skimage.draw import polygon\n"
     "    return polygon(*args, **kwargs)\n", 1),
]

REPORT_STUB = '''# -*- coding: utf-8 -*-
"""Stand-in for OCED's engine/report/clean_report.py (the PDF cleaning report), written by tools/sync_engine.py.

This package returns the clean shapefile and a JSON summary; it does not build the PDF report, so reportlab, PyMuPDF
and matplotlib are not needed. The cleaning module calls make_report() at the end of every run: here it does nothing.
"""


def make_report(R, path, *args, **kwargs):
    """No PDF report in this package (see the module docstring). Returns None and writes nothing."""
    return None
'''


def sha256(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def git(repo: str, *args: str) -> bytes:
    r = subprocess.run(["git", "-C", repo, *args], stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if r.returncode != 0:
        raise SystemExit(f"git {' '.join(args)} failed in {repo}: {r.stderr.decode('utf-8', 'replace').strip()}")
    return r.stdout


def transform(src_path: str, raw: bytes, tests: bool = False) -> tuple[bytes, list[str]]:
    """The committed bytes of one file -> the bytes written here, and the names of the changes applied."""
    text = raw.decode("utf-8")
    applied = []
    for path, what, old, new, count in PATCHES:
        if path != src_path:
            continue
        n = text.count(old)
        if n != count:
            raise SystemExit(f"{src_path}: the patch '{what}' expects {count} match(es) of {old!r}, found {n}. OCED "
                             "changed here: review the patch in tools/sync_engine.py before syncing")
        text = text.replace(old, new)
        applied.append(what)
    text, n = IMPORT_RE.subn(lambda m: m.group(1) + PKG, text)
    if n:
        applied.append(f"package name: {n} import line(s) 'engine' -> '{PKG}'")
    if tests:
        text, n = TESTS_IMPORT_RE.subn(lambda m: m.group(1) + TEST_PKG + "." + m.group(2), text)
        if n:
            applied.append(f"package name: {n} import line(s) 'tests.' -> '{TEST_PKG}.'")
        if src_path.startswith("engine/formats/"):
            text, n = REL_IMPORT_RE.subn(lambda m: m.group(1) + PKG + ".formats" + m.group(2), text)
            if n:
                applied.append(f"{n} relative import(s) of engine/formats made absolute ({PKG}.formats)")
    return text.encode("utf-8"), applied


def check_imports(dest_rel: str, data: bytes) -> list[str]:
    """Problems left in a copied module: an import of the top-level `engine` package, or an importlib call with it."""
    probs = []
    tree = ast.parse(data.decode("utf-8"), filename=dest_rel)
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for a in node.names:
                if a.name == "engine" or a.name.startswith("engine."):
                    probs.append(f"{dest_rel}:{node.lineno}: import {a.name}")
        elif isinstance(node, ast.ImportFrom) and node.level == 0:
            mod = node.module or ""
            if mod == "engine" or mod.startswith("engine."):
                probs.append(f"{dest_rel}:{node.lineno}: from {mod} import ...")
        elif isinstance(node, ast.Call) and getattr(node.func, "attr", "") == "import_module":
            for a in node.args:
                for c in ast.walk(a):
                    if isinstance(c, ast.Constant) and isinstance(c.value, str) and c.value.startswith("engine"):
                        probs.append(f"{dest_rel}:{node.lineno}: import_module({c.value!r} ...)")
    return probs


def imported_engine_modules(data: bytes) -> set[str]:
    """The modules of this package's engine a copied module imports (absolute or relative), as dotted names."""
    out = set()
    for node in ast.walk(ast.parse(data.decode("utf-8"))):
        if isinstance(node, ast.ImportFrom) and node.level == 0 and (node.module or "").startswith(PKG):
            base = node.module
            out.add(base)
            out.update(f"{base}.{a.name}" for a in node.names)
        elif isinstance(node, ast.Import):
            out.update(a.name for a in node.names if a.name.startswith(PKG))
    return out


def write(path: str, data: bytes):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)


def oced_version(oced: str, commit: str) -> str | None:
    """OCED's version at a commit: VERSION = "x.y.z" of app/brand.py (None when it is not there)."""
    r = subprocess.run(["git", "-C", oced, "show", f"{commit}:app/brand.py"], stdout=subprocess.PIPE,
                       stderr=subprocess.PIPE)
    if r.returncode != 0:
        return None
    m = re.search(r'^VERSION\s*=\s*["\']([^"\']+)["\']', r.stdout.decode("utf-8", "replace"), re.M)
    return m.group(1) if m else None


def decoders_of(detect_py: bytes) -> list[str]:
    """The raw-format decoders OCED's engine/formats/detect.py names in its DECODERS list. The engine loads them by
    name at run time (importlib), so no import line shows them: they are read from the list itself."""
    for node in ast.parse(detect_py.decode("utf-8")).body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "DECODERS" for t in node.targets):
            try:
                names = ast.literal_eval(node.value)
            except ValueError:
                break
            if isinstance(names, (list, tuple)) and names and all(isinstance(n, str) for n in names):
                return list(names)
            break
    raise SystemExit("engine/formats/detect.py has no DECODERS list of module names any more: the way OCED loads its "
                     "decoders changed, review decoders_of() in tools/sync_engine.py")


def sync(oced: str, ref: str, expect_subject: str | None, expect_version: str | None = None) -> int:
    oced = os.path.abspath(oced)
    commit = git(oced, "rev-parse", f"{ref}^{{commit}}").decode().strip()
    subject = git(oced, "log", "-1", "--format=%s", commit).decode("utf-8", "replace").strip()
    date = git(oced, "log", "-1", "--format=%cI", commit).decode().strip()
    if expect_subject and expect_subject.lower() not in subject.lower():
        raise SystemExit(f"commit {commit[:12]} is titled {subject!r}, not {expect_subject!r}: not synced")
    version = oced_version(oced, commit)
    if expect_version and version != expect_version:
        raise SystemExit(f"commit {commit[:12]} is OCED {version or '(version not found)'}, not {expect_version}: "
                         "not synced")
    try:
        remote = git(oced, "remote", "get-url", "origin").decode().strip()
    except SystemExit:
        remote = None
    listed = set(git(oced, "ls-tree", "-r", "--name-only", commit).decode("utf-8", "replace").splitlines())
    missing = [p for p in ENGINE_FILES + list(TEST_FILES) if p not in listed]
    if missing:
        raise SystemExit(f"commit {commit[:12]} has no {', '.join(missing)}: the engine's layout changed, review "
                         "ENGINE_FILES in tools/sync_engine.py")
    # every decoder the engine names is copied, also one OCED gained after ENGINE_FILES was written
    decoders = decoders_of(git(oced, "show", f"{commit}:engine/formats/detect.py"))
    engine_files = list(ENGINE_FILES)
    new_decoders = []
    for fid in decoders:
        p = f"engine/formats/{fid}.py"
        if p not in listed:
            raise SystemExit(f"commit {commit[:12]}: DECODERS names {fid!r} but there is no {p}")
        if p not in engine_files:
            engine_files.append(p)
            new_decoders.append(fid)
    files, probs, vendored = {}, [], {}
    for src in engine_files:
        raw = git(oced, "show", f"{commit}:{src}")
        data, applied = transform(src, raw)
        rel = src[len("engine/"):]
        probs += check_imports(rel, data)
        vendored[rel] = data
        files[rel] = {"source": src, "sha256_source": sha256(raw), "sha256": sha256(data), "changes": applied}
    # every engine module a copied module imports must be copied too (or be the report stub)
    have = {PKG + "." + r[:-3].replace("/", ".").removesuffix(".__init__") for r in vendored}
    have |= {PKG, PKG + ".report", PKG + ".report.clean_report"}
    for rel, data in vendored.items():
        for mod in imported_engine_modules(data):
            if mod in have or not _is_module(mod, listed):
                continue                     # copied, or a name inside a module (a function, a constant)
            if mod == PKG + ".clean.references":
                continue                     # optional in OCED too (try / except around its import): not copied
            probs.append(f"{rel}: imports {mod}, which is not in ENGINE_FILES")
    if probs:
        raise SystemExit("not synced:\n  " + "\n  ".join(sorted(set(probs))))
    # write: the engine folder holds exactly these files
    for dp, dn, fn in os.walk(DEST):
        dn[:] = [d for d in dn if d != "__pycache__"]
        for f in fn:
            if f.endswith(".py") or f == os.path.basename(MANIFEST):
                os.remove(os.path.join(dp, f))
    for rel, data in vendored.items():
        write(os.path.join(DEST, *rel.split("/")), data)
    stub = REPORT_STUB.encode("utf-8")
    write(os.path.join(DEST, "report", "__init__.py"), b"")
    write(os.path.join(DEST, "report", "clean_report.py"), stub)
    files["report/__init__.py"] = {"source": None, "sha256_source": None, "sha256": sha256(b""),
                                   "changes": ["not from OCED: empty package marker of the report stub"]}
    files["report/clean_report.py"] = {"source": None, "sha256_source": None, "sha256": sha256(stub),
                                       "changes": ["not from OCED: do-nothing make_report() in place of the PDF report"]}
    manifest = {
        "what": "The cleaning engine of OCED (Olds College Extract Data), copied by tools/sync_engine.py. Do not edit "
                "the files in this folder: change OCED and sync again.",
        "source_repository": remote, "commit": commit, "commit_subject": subject, "commit_date": date,
        "oced_version": version, "synced_at": _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "package": PKG, "decoders": decoders,
        "patches": [{"file": p, "what": w} for p, w, _o, _n, _c in PATCHES]
        + [{"file": "*", "what": f"import lines of the top-level package 'engine' renamed to '{PKG}'"},
           {"file": "report/clean_report.py", "what": "stub: no PDF report (OCED's engine/report is not copied)"}],
        "not_copied": ["engine/report/* (PDF report)", "engine/works.py (the app's saved works)",
                       "engine/clean/references.py (literature citations of the report; optional in OCED)",
                       "engine/formats/*_write.py, native_write.py, isoxml_write.py (monitor-format writers)"],
        "files": files,
    }
    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, indent=1, sort_keys=True)
        f.write("\n")
    # test support
    tfiles = {}
    os.makedirs(TEST_DEST, exist_ok=True)
    for src, name in TEST_FILES.items():
        raw = git(oced, "show", f"{commit}:{src}")
        data, applied = transform(src, raw, tests=True)
        bad = check_imports(name, data)
        if bad:
            raise SystemExit("test support not synced:\n  " + "\n  ".join(bad))
        write(os.path.join(TEST_DEST, name), data)
        tfiles[name] = {"source": src, "sha256_source": sha256(raw), "sha256": sha256(data), "changes": applied}
    write(os.path.join(TEST_DEST, "__init__.py"),
          b'"""OCED\'s synthetic-data generators (made-up numbers only), copied by tools/sync_engine.py."""\n')
    with open(TEST_MANIFEST, "w", encoding="utf-8", newline="\n") as f:
        json.dump({"commit": commit, "oced_version": version, "files": tfiles}, f, indent=1, sort_keys=True)
        f.write("\n")
    print(f"synced OCED {version or '?'} ({commit[:12]} {subject!r}): {len(vendored)} engine files + the report stub "
          f"-> {os.path.relpath(DEST, ROOT)}; {len(tfiles)} test-support files -> {os.path.relpath(TEST_DEST, ROOT)}")
    if new_decoders:
        print(f"NEW decoder(s) in OCED, copied: {', '.join(new_decoders)}. Still to do by hand: a synthetic upload of "
              "each in tests/test_raw_formats.py (its generator in TEST_FILES above), and the format in the README")
    return 0


def _is_module(mod: str, listed: set) -> bool:
    """True when the dotted name is a module file of OCED's engine (not a function or constant of a module)."""
    rel = "engine/" + mod[len(PKG) + 1:].replace(".", "/")
    return (rel + ".py") in listed or (rel + "/__init__.py") in listed


def check() -> int:
    """The copied files against the manifests; prints every difference. 0 = identical."""
    bad = []
    for man, base in ((MANIFEST, DEST), (TEST_MANIFEST, TEST_DEST)):
        if not os.path.exists(man):
            bad.append(f"missing {os.path.relpath(man, ROOT)} (run the sync)")
            continue
        with open(man, encoding="utf-8") as f:
            files = json.load(f)["files"]
        for rel, info in files.items():
            p = os.path.join(base, *rel.split("/"))
            if not os.path.exists(p):
                bad.append(f"missing {os.path.relpath(p, ROOT)}")
                continue
            with open(p, "rb") as fh:
                if sha256(fh.read()) != info["sha256"]:
                    bad.append(f"changed since the sync: {os.path.relpath(p, ROOT)}")
        on_disk = set()
        for dp, dn, fn in os.walk(base):
            dn[:] = [d for d in dn if d != "__pycache__"]
            on_disk |= {os.path.relpath(os.path.join(dp, f), base).replace(os.sep, "/") for f in fn if f.endswith(".py")}
        extra = on_disk - set(files) - ({"__init__.py"} if base == TEST_DEST else set())
        bad += [f"not in the manifest: {os.path.relpath(os.path.join(base, e), ROOT)}" for e in sorted(extra)]
    for b in bad:
        print(b)
    if not bad:
        print("the copied engine and test support match their manifests")
    return 1 if bad else 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Copy OCED's cleaning engine into this package from a git checkout.")
    ap.add_argument("--oced", help="path to a clone of the OCED repository")
    ap.add_argument("--ref", default="HEAD", help="commit, tag or branch to copy from (default HEAD)")
    ap.add_argument("--expect-subject", default=None,
                    help="refuse the sync unless the commit's title contains this text (e.g. 'OCED 0.3.0')")
    ap.add_argument("--expect-version", default=None,
                    help="refuse the sync unless OCED's version at the commit (app/brand.py) is this one (e.g. 0.3.0)")
    ap.add_argument("--check", action="store_true", help="only compare the copied files with the manifest")
    a = ap.parse_args(argv)
    if a.check:
        return check()
    if not a.oced:
        ap.error("--oced is required (or --check)")
    return sync(a.oced, a.ref, a.expect_subject, a.expect_version)


if __name__ == "__main__":
    sys.exit(main())
